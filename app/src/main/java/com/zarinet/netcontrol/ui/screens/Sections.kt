/**
 * تعريف قسم عام من RouterOS: المسار، الحقل الرئيسي، والحقول المعروضة (مفتاح → تسمية عربية).
 * شاشة ResourceScreen تعرض أي قسم بهذه الطريقة (عرض/إضافة/تعديل/حذف/تعطيل).
 *
 * readOnly: حقول تُعرض فقط ولا تُرسل عند الحفظ.
 * card: الحقول المعروضة في بطاقة العنصر (فارغة = كل الحقول).
 * rowAction: أمر إضافي على كل عنصر (مثل make-static أو renew).
 */
data class Section(
    val key: String,
    val title: String,
    val subtitle: String,
    val path: String,
    val primary: List<String>,
    val fields: List<Pair<String, String>>,
    val color: Color,
    val icon: ImageVector,
    val canAdd: Boolean = true,
    val canEdit: Boolean = true,
    val canDelete: Boolean = true,
    val canToggle: Boolean = true,
    val newestFirst: Boolean = false,
    val limit: Int = 0,
    val readOnly: Set<String> = emptySet(),
    val card: List<String> = emptyList(),
    val rowAction: RowAction? = null
)

/** أمر إضافي يظهر على العنصر عندما يتحقق الشرط visible. */
